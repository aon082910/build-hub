def _swatch(color: tuple[int, int, int], seed: int, size: int = 500) -> bytes:
    """Distinct placeholder art per product.

    Deliberately different *shapes*, not just different colours: perceptual hashing
    keys on structure, so recolouring one motif would leave every demo product a
    near-match of every other and make reverse image search look broken.
    """
    from PIL import Image as PILImage, ImageDraw

    img = PILImage.new("RGB", (size, size), (245, 246, 248))
    d = ImageDraw.Draw(img)
    m = 60

    if seed == 0:        # stepper motor - square body, round shaft, corner bolts
        d.rounded_rectangle([m, m, size - m, size - m], radius=14, fill=color)
        d.ellipse([size // 2 - 90, size // 2 - 90, size // 2 + 90, size // 2 + 90],
                  fill=(35, 35, 40))
        d.ellipse([size // 2 - 30, m - 20, size // 2 + 30, m + 40], fill=(60, 60, 66))
        for cx, cy in ((m + 40, m + 40), (size - m - 40, m + 40),
                       (m + 40, size - m - 40), (size - m - 40, size - m - 40)):
            d.ellipse([cx - 16, cy - 16, cx + 16, cy + 16], fill=(230, 230, 234))
    elif seed == 2:      # probe/sensor - small body with a pin tip
        d.rounded_rectangle([size // 2 - 70, m, size // 2 + 70, size // 2 + 40],
                             radius=20, fill=color)
        d.rectangle([size // 2 - 14, size // 2 + 40, size // 2 + 14, size - m],
                     fill=(35, 35, 40))
        d.ellipse([size // 2 - 22, size - m - 20, size // 2 + 22, size - m + 20],
                   fill=(240, 240, 245))
    else:                # soldering iron - long body with a tapered tip
        d.rounded_rectangle([m, size // 2 - 40, size - m - 90, size // 2 + 40],
                             radius=22, fill=color)
        d.polygon([(size - m - 90, size // 2 - 30), (size - m, size // 2),
                    (size - m - 90, size // 2 + 30)], fill=(210, 210, 214))
        d.rectangle([m + 20, size // 2 - 16, m + 90, size // 2 + 16], fill=(30, 30, 36))

    buf = io.BytesIO()
    img.save(buf, "PNG")
    return buf.getvalue()


IMAGES = {
    "stepper": _swatch((60, 64, 74), 0),
    "probe": _swatch((28, 150, 120), 2),
    "iron": _swatch((208, 118, 26), 4),
}


class _LocalImageFetcher:
    """Serves the generated bytes instead of hitting the network."""

    def download(self, url: str, referer: str | None = None) -> bytes:
        for key, data in IMAGES.items():
            if key in url:
                return data
        raise RuntimeError(f"no demo image for {url}")

    def close(self) -> None:
        pass


